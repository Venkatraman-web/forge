#!/bin/bash
# Writes inventory/group_vars/all/neon.local.yml (git-ignored) with the Neon host names that /etc/hosts must pin to a front-door address.
# It reads only the HOST NAMES out of the connection strings in ~/.forge-aws/secrets; passwords are never copied.
# The front-door addresses are the ones measured to be fastest from the test machines (override with the environment variables).
set -euo pipefail
cd "$(dirname "$0")"
main_ip="${NEON_MAIN_FRONT_DOOR:-3.106.69.51}"          # shop, results and payments projects
inventory_ip="${NEON_INVENTORY_FRONT_DOOR:-54.206.85.193}"  # the inventory project
host() { grep "^$1=" ~/.forge-aws/secrets | head -1 | sed -E 's#^[^=]*=[a-z]+://[^@]*@([^/:?]+).*#\1#'; }
{
  echo "# generated by make-vars.sh from the host names in ~/.forge-aws/secrets; do not edit, do not commit"
  echo "neon_pins:"
  for k in NEON_SHOP_DIRECT_URL NEON_RESULTS_DIRECT_URL NEON_PAYMENTS_DIRECT_URL; do echo "  - { host: $(host $k), ip: $main_ip }"; done
  echo "  - { host: $(host NEON_INVENTORY_DIRECT_URL), ip: $inventory_ip }"
} > inventory/group_vars/all/neon.local.yml
echo "inventory/group_vars/all/neon.local.yml written ($(grep -c 'host:' inventory/group_vars/all/neon.local.yml) pins)"
