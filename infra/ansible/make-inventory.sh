#!/bin/bash
# Builds inventory/hosts.ini from AWS (read-only: describe-instances), so public addresses, which change on every
# start, are never typed by hand. Only instances whose Name tag is listed below and that are running are included.
# Needs the AWS CLI signed in (aws login) and the region ap-southeast-2.
set -euo pipefail
cd "$(dirname "$0")"
region=ap-southeast-2
aws ec2 describe-instances --region "$region" \
  --filters Name=instance-state-name,Values=running \
  --query 'Reservations[].Instances[].[Tags[?Key==`Name`]|[0].Value, PublicIpAddress, PrivateIpAddress, InstanceId]' --output text |
python3 -c '
import sys
role = {"forge-m7": "forge", "forge-db2": "forge_db", "cart-db": "cart_db", "shop": "shop", "workers": "workers", "loadgen": "loadgen"}
rows = [l.split() for l in sys.stdin if l.strip()]
print("# generated by make-inventory.sh from AWS; do not edit, do not commit")
print("[machines]")
for name, pub, priv, iid in sorted(rows):
    if name in role:
        print(f"{role[name]} ansible_host={pub} private_ip={priv} instance_id={iid}")
'  > inventory/hosts.ini
echo "inventory/hosts.ini written:"; grep -c ansible_host inventory/hosts.ini | sed 's/$/ machines/'
